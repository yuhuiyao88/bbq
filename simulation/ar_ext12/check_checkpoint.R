# Rscript check_checkpoint.R <checkpoint> <scratch-dir>
args <- commandArgs(TRUE)
stopifnot(length(args) == 2L, file.exists(args[1]))
script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])
here <- dirname(normalizePath(script, winslash = "/"))
scratch <- normalizePath(args[2], winslash = "/", mustWork = FALSE)
dir.create(scratch, recursive = TRUE, showWarnings = FALSE)
sup <- new.env(parent = globalenv())
source(file.path(here, "run_arext12_supervised.R"), local = sup)
sup$TV11_SCRIPT_DEFAULT <- file.path(here, "simulation_arext12.R")
stopifnot(sup$.tv11_schema_ok(args[1]))
cat("PASS: real driver checkpoint accepted by supervisor\n")
obj <- readRDS(args[1]); obj$basis_sig <- "incompatible-five-quantile-study"
bad <- file.path(scratch, "bad_checkpoint.rds"); saveRDS(obj, bad)
stopifnot(!sup$.tv11_schema_ok(bad))
cat("PASS: incompatible checkpoint fingerprint rejected\n")
for (name in c("build_app_csv_from_tasks.R", "run_arext12_supervised.R", "simulation_arext12.R"))
  stopifnot(file.copy(file.path(here, name), file.path(scratch, name), overwrite = TRUE))
stopifnot(file.copy(args[1], file.path(scratch, basename(args[1])), overwrite = TRUE))
Sys.setenv(AREXT12_WORK_DIR = scratch)
status <- system2(file.path(R.home("bin"), "Rscript.exe"),
                   c("--vanilla", shQuote(file.path(scratch, "build_app_csv_from_tasks.R"))))
stopifnot(status == 0L)
csv <- list.files(scratch, "app.*\\.csv$", full.names = TRUE)
stopifnot(length(csv) > 0L)
cat("PASS: real driver checkpoint aggregates successfully\n")
cat("CHECKPOINT AND AGGREGATION CHECKS PASSED\n")
